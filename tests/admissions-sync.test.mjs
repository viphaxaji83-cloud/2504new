test('sync cache is atomic, persistent and protected against manual changes',async t=>{
 const dir=await mkdtemp(path.join(os.tmpdir(),'mgtu-sync-test-'));let db=openStore(dir),bad=false,calls=0;
 let service=admissionsService(db,{fetcher:async()=>{calls++;return new Response(bad?'broken':html(rows));}});
 t.after(async()=>{await service.stop();db.close();assert.ok(path.basename(dir).startsWith('mgtu-sync-test-')&&path.resolve(dir).startsWith(path.resolve(os.tmpdir())+path.sep));await rm(dir,{recursive:true,force:true});});
 const before=db.prepare('SELECT * FROM content').get();
 await Promise.all([service.sync(),service.sync()]);assert.equal(calls,1);assert.equal(service.status().matched,58);
 assert.equal(db.prepare('SELECT revision FROM content').get().revision,before.revision+1);
 const content=service.overlay(JSON.parse(before.json));assert.equal(content.programs.pi.admission.rows[0][1],'42');
 assert.equal(content.programs.pi.description,JSON.parse(before.json).programs.pi.description);
 await service.sync();assert.equal(db.prepare('SELECT revision FROM content').get().revision,before.revision+1);
 bad=true;await service.sync();assert.equal(service.status().error,'SOURCE_SCHEMA_CHANGED');assert.equal(service.overlay(JSON.parse(before.json)).programs.pi.admission.rows[0][1],'42');
 assert.throws(()=>service.assertUnlocked([{path:'programs.pi.admission.ege'}]),{status:403});
 assert.throws(()=>service.assertUnlocked([{path:'programs.pi.document'}]),{status:403});
 assert.doesNotThrow(()=>service.assertUnlocked([{path:'programs.pi.description'}]));
 await service.stop();db.close();db=openStore(dir);service=admissionsService(db);assert.equal(service.status().matched,58);
});
